// Writes src/space/casefold-data.ts from the Unicode CaseFolding.txt file.
// Usage: node scripts/gen-casefold.mjs path/to/CaseFolding.txt

import { readFileSync, writeFileSync } from "node:fs";

const [source] = process.argv.slice(2);
if (!source) {
  console.error("usage: node scripts/gen-casefold.mjs path/to/CaseFolding.txt");
  process.exit(2);
}

const text = readFileSync(source, "utf8");
const version = /^# CaseFolding-(\d+\.\d+\.\d+)\.txt/m.exec(text)?.[1];
if (!version) throw new Error("no CaseFolding version header in " + source);

const entries = [];
for (const line of text.split("\n")) {
  const [code, status, mapping] = line.split("#")[0].split(";").map((field) => field.trim());
  if (status !== "C" && status !== "F") continue;
  entries.push(`${code.toLowerCase()}:${mapping.toLowerCase()}`);
}

const out = `// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by scripts/gen-casefold.mjs from CaseFolding-${version}.txt (statuses C and F). Do not edit.

export const UNICODE_VERSION = "${version}";

export const CASE_FOLDING =
  "${entries.join(",")}";
`;
writeFileSync(new URL("../src/space/casefold-data.ts", import.meta.url), out);
console.log(`wrote ${entries.length} mappings from Unicode ${version}`);
