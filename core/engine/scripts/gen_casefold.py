"""Writes src/casefold_data.rs from the Unicode CaseFolding.txt given as the first argument (statuses C and F)."""

import pathlib
import re
import sys

source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
version = re.search(r"^# CaseFolding-(\S+)\.txt", source, re.M).group(1)
rows = []
for line in source.splitlines():
    fields = [field.strip() for field in line.split("#", 1)[0].split(";")]
    if len(fields) < 3 or fields[1] not in ("C", "F"):
        continue
    mapping = "".join(f"\\u{{{cp.lower()}}}" for cp in fields[2].split())
    rows.append(f'    (0x{fields[0].lower()}, "{mapping}"),')

out = pathlib.Path(__file__).resolve().parent.parent / "src" / "casefold_data.rs"
out.write_text(
    "// SPDX-License-Identifier: Apache-2.0\n"
    f"// Generated by scripts/gen_casefold.py from CaseFolding-{version}.txt (statuses C and F). Do not edit.\n\n"
    "pub(crate) static CASE_FOLDING: &[(u32, &str)] = &[\n" + "\n".join(rows) + "\n];\n",
    encoding="utf-8",
)
